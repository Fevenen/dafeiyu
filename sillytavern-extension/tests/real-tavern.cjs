const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = process.env.PET_TEST_DIR;
app.setPath('userData', path.join(root, 'browser-profile'));
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function main() {
    const win = new BrowserWindow({ show: false, width: 1320, height: 1000, webPreferences: { sandbox: false, contextIsolation: true, backgroundThrottling: false, offscreen: true } });
    const errors = [];
    win.webContents.on('console-message', (_, level, message) => { if (level === 3) errors.push(message.slice(0, 250)); });
    const js = code => win.webContents.executeJavaScript(code, true);
    async function until(code, label, milliseconds = 45000) {
        const end = Date.now() + milliseconds;
        while (Date.now() < end) { try { if (await js(code)) return; } catch {} await wait(100); }
        throw new Error('Timed out: ' + label + ' ' + await js('document.querySelector("#dafeiyu-tavern-panel [data-status]")?.textContent'));
    }
    await win.loadURL('http://127.0.0.1:8123');
    await until('!!globalThis.SillyTavern?.getContext && !!document.getElementById("dafeiyu-tavern-panel")', 'extension loaded');
    await js('document.querySelectorAll("dialog[open] .popup-button-ok").forEach(button=>button.click())');
    await js(`(async()=>{
        document.querySelector('#dialogue_popup_ok')?.click();
        const c=SillyTavern.getContext();
        const response=await fetch('/api/characters/create',{method:'POST',headers:c.getRequestHeaders(),body:JSON.stringify({ch_name:'Fixture Innkeeper',description:'TEST_HIDDEN_CARD_SECRET: the owner is a ghost.',first_mes:'老板说：“楼上没有住客，但夜里别上去。”',personality:'谨慎',scenario:'旅馆前台'})});
        if(!response.ok)throw new Error(await response.text());
        await c.getCharacters();
        const id=SillyTavern.getContext().characters.findIndex(x=>x.name==='Fixture Innkeeper');
        if(id<0)throw new Error('Fixture character missing');
        await c.selectCharacterById(id);
        document.querySelector('#dialogue_popup_ok')?.click();
        $('#main_api').val('openai').trigger('change');
        $('#chat_completion_source').val('custom').trigger('change');
        $('#custom_api_url_text').val('http://127.0.0.1:18424/v1').trigger('input');
        $('#custom_model_id').val('fixture-model').trigger('input');
        const settings=SillyTavern.getContext().chatCompletionSettings;
        Object.assign(settings,{chat_completion_source:'custom',custom_url:'http://127.0.0.1:18424/v1',custom_model:'fixture-model',stream_openai:false});
        await fetch('/api/secrets/write',{method:'POST',headers:c.getRequestHeaders(),body:JSON.stringify({key:'api_key_custom',value:'fixture-only-key',label:'Test fixture'})});
        const secrets=await import('/scripts/secrets.js');await secrets.readSecretState();
        SillyTavern.getContext().powerUserSettings.persona_description='一个调查员，只知道可见剧情。';
        $('#api_button_openai').trigger('click');
        const panel=document.getElementById('dafeiyu-tavern-panel');panel.hidden=false;
        const base=panel.querySelector('[data-base]');base.value='http://127.0.0.1:18424';base.dispatchEvent(new Event('change'));
    })()`);
    await until('SillyTavern.getContext().chat.length>0', 'fixture chat ready');
    await js('document.querySelectorAll("dialog[open] .popup-button-ok").forEach(button=>button.click())');
    await until('SillyTavern.getContext().onlineStatus!=="no_connection"', 'mock model connection ready');
    const initial = await js('SillyTavern.getContext().chat.length');
    const baseline = await (await fetch('http://127.0.0.1:18424/test/status')).json();
    assert.equal(await js('document.querySelector("#dafeiyu-tavern-toolbar [data-badge]").textContent'), '关闭');
    await js('document.querySelector("#dafeiyu-tavern-panel [data-enable]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-status]").textContent.includes("陪玩中")', 'companion enabled');
    await js('document.querySelector("#dafeiyu-tavern-panel [data-observe]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-comments]").textContent.includes("老板的话有矛盾")', 'companion comment');
    assert.equal(await js('SillyTavern.getContext().chat.length'), initial);
    await js('document.querySelector("#dafeiyu-tavern-panel [data-question]").value="这次怎么选？";document.querySelector("#dafeiyu-tavern-panel [data-ask]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-comments]").textContent.includes("核对楼上的脚步声")', 'companion question');
    const commentsBefore = (await (await fetch('http://127.0.0.1:18424/test/status')).json()).counts.comment;
    await js(`(async()=>{
        document.querySelector('#dafeiyu-tavern-panel [data-auto]').checked=false;
        const c=SillyTavern.getContext();
        c.chat.push({name:'Fixture Innkeeper',is_user:false,is_system:false,mes:'独立同步线索：红钥匙在柜台。',send_date:Date.now(),extra:{}});
        await c.saveChat();
        await c.eventSource.emit(c.eventTypes.GENERATION_ENDED);
    })()`);
    await until(`fetch('http://127.0.0.1:18424/test/status').then(r=>r.json()).then(s=>s.shared_text.includes('独立同步线索'))`, 'silent mode still synchronizes the latest scene');
    assert.equal((await (await fetch('http://127.0.0.1:18424/test/status')).json()).counts.comment, commentsBefore);
    await js(`(async()=>{ const c=SillyTavern.getContext();c.chat.pop();await c.saveChat();await c.eventSource.emit(c.eventTypes.MESSAGE_DELETED);document.querySelector('#dafeiyu-tavern-panel [data-auto]').checked=true; })()`);
    await wait(350);
    await js('document.querySelector("#dafeiyu-tavern-panel [data-draft]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-action]").value.includes("二楼的钥匙") && !document.querySelector("#dafeiyu-tavern-panel [data-submit]").disabled', 'draft ready');
    assert.equal(await js('SillyTavern.getContext().chat.length'), initial);
    assert.equal(await js('document.getElementById("send_textarea").value'), '');
    await js('document.querySelector("#dafeiyu-tavern-panel [data-action]").value="我先观察钥匙的形状，再问老板。";document.querySelector("#dafeiyu-tavern-panel [data-submit]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-status]").textContent.includes("本轮结束")', 'one round completed', 60000);
    const afterSingle = await js('SillyTavern.getContext().chat.length');
    assert.equal(afterSingle, initial + 2);
    assert.equal(await js('SillyTavern.getContext().chat.filter(x=>x.is_user).at(-1).mes'), '我先观察钥匙的形状，再问老板。');
    await js('document.querySelector("#dafeiyu-tavern-panel [data-turns]").value="3";document.querySelector("#dafeiyu-tavern-panel [data-run]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-status]").textContent.includes("授权轮数已完成")', 'three rounds completed', 60000);
    assert.equal(await js('SillyTavern.getContext().chat.length'), afterSingle + 6);
    const afterContinuous = await js('SillyTavern.getContext().chat.length');
    await fetch('http://127.0.0.1:18424/test/control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action: 1200 }) });
    await js('document.querySelector("#dafeiyu-tavern-panel [data-single]").click()');
    await until(`fetch('http://127.0.0.1:18424/test/status').then(r=>r.json()).then(s=>s.counts.action>=${baseline.counts.action + 5})`, 'delayed action started');
    await js('document.getElementById("send_textarea").value="我自己来";document.getElementById("send_textarea").dispatchEvent(new Event("input",{bubbles:true}))');
    await wait(1500);
    assert.equal(await js('SillyTavern.getContext().chat.length'), afterContinuous);
    assert.equal(await js('document.getElementById("send_textarea").value'), '我自己来');
    await fetch('http://127.0.0.1:18424/test/control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ npc: 1500 }) });
    await js('document.getElementById("send_textarea").value="";document.querySelector("#dafeiyu-tavern-panel [data-single]").click()');
    await until(`fetch('http://127.0.0.1:18424/test/status').then(r=>r.json()).then(s=>s.counts.npc>=${baseline.counts.npc + 5})`, 'delayed NPC started');
    await js('document.getElementById("send_textarea").value="这轮我接手";document.getElementById("send_textarea").dispatchEvent(new Event("input",{bubbles:true}))');
    await wait(1800);
    assert.equal(await js('SillyTavern.getContext().chat.length'), afterContinuous + 1);
    assert.equal(await js('document.getElementById("send_textarea").value'), '这轮我接手');
    const beforeInput = await js('SillyTavern.getContext().chat.length');
    await js('document.getElementById("send_textarea").value="我自己正在输入";document.getElementById("send_textarea").dispatchEvent(new Event("input",{bubbles:true}));document.querySelector("#dafeiyu-tavern-panel [data-single]").click()');
    await until('document.querySelector("#dafeiyu-tavern-panel [data-status]").textContent.includes("不会覆盖")', 'human input protection');
    assert.equal(await js('SillyTavern.getContext().chat.length'), beforeInput);
    assert.equal(await js('document.getElementById("send_textarea").value'), '我自己正在输入');
    await js('document.querySelector("#dafeiyu-tavern-panel [data-off]").click()');
    await until('document.querySelector("#dafeiyu-tavern-toolbar [data-badge]").textContent==="关闭"', 'disabled');
    await js('document.querySelectorAll("dialog[open] .popup-button-ok").forEach(button=>button.click());new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
    const image = await win.webContents.capturePage(); fs.writeFileSync(path.join(root, 'tavern-ui.png'), image.toPNG());
    await new Promise(resolve => { win.webContents.once('did-finish-load', resolve); win.reload(); });
    await until('!!document.querySelector("#dafeiyu-tavern-toolbar [data-badge]")', 'reload');
    assert.equal(await js('document.querySelector("#dafeiyu-tavern-toolbar [data-badge]").textContent'), '关闭');
    const counts = await (await fetch('http://127.0.0.1:18424/test/status')).json();
    assert.equal(counts.counts.action - baseline.counts.action, 6); assert.equal(counts.counts.npc - baseline.counts.npc, 5);
    const report = { passed: true, initial, afterSingle, finalMessages: beforeInput, counts: counts.counts, errors };
    fs.writeFileSync(path.join(root, 'result.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report)); win.destroy(); app.exit(0);
}
app.whenReady().then(main).catch(error => { fs.writeFileSync(path.join(root, 'failure.txt'), error.stack); console.error(error.stack); app.exit(1); });
